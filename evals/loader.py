"""Load and cross-validate the eval dataset.

Two ticket sets share one validation:

- the **held-out** set, `tickets.json`: 22 hand-written tickets, the
  permanent sanity check, never used for tuning;
- the **synthetic** set, `synthetic/batch_*.json`: generated by
  `evals/generate/`, each batch entering the set only once its labels have
  been reviewed (`"reviewed": true`). Its customers live in
  `synthetic/customers.json`.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

from evals.schema import Customer, Outcome, Ticket, Tool

DATASET_DIR = Path(__file__).parent / "dataset"
POLICY_DIR = DATASET_DIR / "policies"
TICKETS_PATH = DATASET_DIR / "tickets.json"
CUSTOMERS_PATH = DATASET_DIR / "customers.json"
SYNTHETIC_DIR = DATASET_DIR / "synthetic"
SYNTHETIC_CUSTOMERS = "customers.json"

_FRONTMATTER_ID = re.compile(r"^policy_id:\s*(\S+)\s*$", re.MULTILINE)


def load_policy_ids(policy_dir: Path = POLICY_DIR) -> set[str]:
    """Policy IDs declared in the corpus, checked against their filenames."""
    ids: set[str] = set()
    for path in sorted(policy_dir.glob("POL-*.md")):
        match = _FRONTMATTER_ID.search(path.read_text(encoding="utf-8"))
        if not match:
            raise ValueError(f"{path.name}: no policy_id in frontmatter")
        declared = match.group(1)
        if declared != path.stem:
            raise ValueError(
                f"{path.name}: declares policy_id {declared!r}, filename says {path.stem!r}"
            )
        ids.add(declared)
    if not ids:
        raise ValueError(f"no policy documents found in {policy_dir}")
    return ids


def load_customers(customers_path: Path = CUSTOMERS_PATH) -> dict[str, Customer]:
    """Account fixtures backing `lookup_customer` and `search_past_tickets`."""
    raw = json.loads(customers_path.read_text(encoding="utf-8"))
    customers = {cid: Customer.model_validate(rec) for cid, rec in raw.items()}
    mismatched = [cid for cid, c in customers.items() if c.customer_id != cid]
    if mismatched:
        raise ValueError(f"customer records keyed inconsistently: {mismatched}")
    return customers


def load_all_customers(
    customers_path: Path = CUSTOMERS_PATH, synthetic_dir: Path = SYNTHETIC_DIR
) -> dict[str, Customer]:
    """Held-out and synthetic customers together, as `lookup_customer` serves
    them. An id in both files is an error, not a silent override."""
    customers = load_customers(customers_path)
    synthetic_path = synthetic_dir / SYNTHETIC_CUSTOMERS
    if synthetic_path.is_file():
        synthetic = load_customers(synthetic_path)
        clash = sorted(customers.keys() & synthetic.keys())
        if clash:
            raise ValueError(f"customer ids in both held-out and synthetic fixtures: {clash}")
        customers |= synthetic
    return customers


def load_tickets(
    tickets_path: Path = TICKETS_PATH,
    policy_dir: Path = POLICY_DIR,
    customers_path: Path = CUSTOMERS_PATH,
) -> list[Ticket]:
    """Parse the held-out tickets and fail loudly on any label the fixtures
    cannot support."""
    raw = json.loads(tickets_path.read_text(encoding="utf-8"))
    tickets = [Ticket.model_validate(item) for item in raw]
    validate(tickets, load_customers(customers_path), load_policy_ids(policy_dir))
    return tickets


def load_synthetic(
    synthetic_dir: Path = SYNTHETIC_DIR,
    policy_dir: Path = POLICY_DIR,
    customers_path: Path = CUSTOMERS_PATH,
    *,
    include_unreviewed: bool = False,
) -> list[Ticket]:
    """Tickets from every reviewed batch, in batch order. Unreviewed batches
    are left out unless `include_unreviewed`, which exists for building and
    checking a batch, never for reporting on one."""
    tickets: list[Ticket] = []
    depends_on: dict[str, str] = {}
    for path in sorted(synthetic_dir.glob("batch_*.json")):
        batch = json.loads(path.read_text(encoding="utf-8"))
        if batch.get("reviewed") is not True and not include_unreviewed:
            continue
        for entry in batch["entries"]:
            ticket = Ticket.model_validate(entry["ticket"])
            tickets.append(ticket)
            if entry.get("depends_on"):
                depends_on[ticket.ticket_id] = entry["depends_on"]
    customers = load_all_customers(customers_path, synthetic_dir)
    validate(tickets, customers, load_policy_ids(policy_dir), depends_on)
    return tickets


def validate(
    tickets: list[Ticket],
    customers: dict[str, Customer],
    known_policies: set[str],
    depends_on: dict[str, str] | None = None,
) -> None:
    """Every check a ticket set must pass, whichever set it is. `depends_on`
    maps a ticket to an earlier one whose memory it relies on."""
    depends_on = depends_on or {}
    duplicates = [tid for tid, n in Counter(t.ticket_id for t in tickets).items() if n > 1]
    if duplicates:
        raise ValueError(f"duplicate ticket ids: {sorted(duplicates)}")

    dangling = {
        t.ticket_id: sorted(set(t.labels.relevant_policy_ids) - known_policies)
        for t in tickets
        if set(t.labels.relevant_policy_ids) - known_policies
    }
    if dangling:
        raise ValueError(f"tickets cite policy ids not in the corpus: {dangling}")

    unknown = sorted({t.customer_id for t in tickets} - customers.keys())
    if unknown:
        raise ValueError(f"tickets reference customers with no fixture: {unknown}")

    # A run-order dependency only works if the earlier ticket runs first, for
    # the same customer, in the same set: memory carries what it said.
    position = {t.ticket_id: i for i, t in enumerate(tickets)}
    by_id = {t.ticket_id: t for t in tickets}
    for tid, earlier in depends_on.items():
        if earlier not in position or position[earlier] >= position[tid]:
            raise ValueError(f"{tid} depends on {earlier!r}, which does not run before it")
        if by_id[earlier].customer_id != by_id[tid].customer_id:
            raise ValueError(f"{tid} depends on {earlier}, a different customer")

    # A tool only belongs in expected_tools if it can actually inform the
    # answer. search_past_tickets against a customer with no history returns
    # empty, and crediting that call would inflate tool-call precision —
    # unless an earlier ticket in the run gives the customer a history.
    barren = [
        t.ticket_id
        for t in tickets
        if Tool.SEARCH_PAST_TICKETS in t.labels.expected_tools
        and not customers[t.customer_id].past_tickets
        and t.ticket_id not in depends_on
    ]
    if barren:
        raise ValueError(
            f"tickets expect search_past_tickets but their customer has no "
            f"prior history: {barren}"
        )

    # ESC-001.4 escalates any request from someone not verified as the account
    # owner. The label owner's ruling (ADR 0010): a general question answered
    # by published policy alone is not such a request. So a non-owner ticket
    # may be labelled other than escalate, but never with a refund, and only
    # with a label_note saying why.
    unowned = [t for t in tickets if t.requester_email != customers[t.customer_id].owner_email]
    refunding = [
        t.ticket_id
        for t in unowned
        if t.labels.outcome is not Outcome.ESCALATE and Tool.ISSUE_REFUND in t.labels.expected_tools
    ]
    if refunding:
        raise ValueError(
            f"tickets from a non-owner requester cannot expect a refund unless labelled "
            f"escalate, per ESC-001.4: {refunding}"
        )
    unexplained = [
        t.ticket_id
        for t in unowned
        if t.labels.outcome is not Outcome.ESCALATE and not t.labels.label_note
    ]
    if unexplained:
        raise ValueError(
            f"tickets from a non-owner requester labelled other than escalate need a "
            f"label_note saying why ESC-001.4 does not apply: {unexplained}"
        )
